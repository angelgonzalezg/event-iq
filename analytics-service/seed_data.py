def get_utc_now():
    """Returns the current date and time in UTC without a time zone for Oracle DATE compatibility"""
    return datetime.now(timezone.utc).replace(tzinfo=None)

def truncate_tables(cursor):
    """ Truncate the tables to remove existing data.
    Truncates tables in reverse order of their foreign keys.
    """
    print("Clearing existing tables...")
    tables = ["comments", "payments", "registrations", "ticket_types", "attendees", "events"]
    
    # Define the ID column names for each table
    id_columns = {
        "comments": "comment_id",
        "payments": "payment_id",
        "registrations": "registration_id",
        "ticket_types": "ticket_type_id",
        "attendees": "attendee_id",
        "events": "event_id"
    }
    
    for table in tables:
        try:
            # Truncate the table
            cursor.execute(f"TRUNCATE TABLE {table}")

            # Reset the counter to 1 
            id_col = id_columns.get(table)
            if id_col:
                cursor.execute(f"ALTER TABLE {table} MODIFY {id_col} GENERATED BY DEFAULT AS IDENTITY (START WITH 1)")
        
        except Exception as e:
            cursor.execute(f"DELETE FROM {table}")
    print("Tables cleared successfully!")

