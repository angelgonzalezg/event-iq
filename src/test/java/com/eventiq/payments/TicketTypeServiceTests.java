package com.eventiq.payments;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatExceptionOfType;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;
import java.util.Optional;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.http.HttpStatus;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.web.server.ResponseStatusException;

import com.eventiq.events.Event;
import com.eventiq.events.EventRepository;

@ExtendWith(MockitoExtension.class)
class TicketTypeServiceTests {

	@Mock
	private TicketTypeRepository ticketTypes;

	@Mock
	private EventRepository events;

	@InjectMocks
	private TicketTypeService service;

	@Test
	void createsATicketTypeForTheRequestedEventAndReturnsTheSavedData() {
		Event event = event(7L);
		BigDecimal price = new BigDecimal("125.75");
		CreateTicketTypeRequest request = new CreateTicketTypeRequest(7L, "General", price);
		TicketType saved = ticketType(21L, event, "General", price);
		when(this.events.findById(7L)).thenReturn(Optional.of(event));
		when(this.ticketTypes.save(any(TicketType.class))).thenReturn(saved);

		TicketTypeResponse response = this.service.create(request);

		ArgumentCaptor<TicketType> submitted = ArgumentCaptor.forClass(TicketType.class);
		verify(this.ticketTypes).save(submitted.capture());
		assertThat(submitted.getValue().getEvent()).isSameAs(event);
		assertThat(submitted.getValue().getName()).isEqualTo("General");
		assertThat(submitted.getValue().getPrice()).isEqualByComparingTo(price);
		assertThat(response).isEqualTo(new TicketTypeResponse(21L, 7L, "General", price));
	}

	@Test
	void rejectsANonexistentEventWithoutSavingATicketType() {
		when(this.events.findById(99L)).thenReturn(Optional.empty());
		CreateTicketTypeRequest request = new CreateTicketTypeRequest(99L, "General", new BigDecimal("125.75"));

		assertThatExceptionOfType(ResponseStatusException.class)
			.isThrownBy(() -> this.service.create(request))
			.satisfies(error -> {
				assertThat(error.getStatusCode()).isEqualTo(HttpStatus.NOT_FOUND);
				assertThat(error.getReason()).isEqualTo("Event not found.");
			});
		verifyNoInteractions(this.ticketTypes);
	}

	@Test
	void listsEveryTicketTypeWithItsOwnEventAndPrice() {
		when(this.ticketTypes.findAll()).thenReturn(List.of(
				ticketType(21L, event(7L), "General", new BigDecimal("125.75")),
				ticketType(22L, event(8L), "Free", BigDecimal.ZERO)));

		assertThat(this.service.findAll()).containsExactlyInAnyOrder(
				new TicketTypeResponse(21L, 7L, "General", new BigDecimal("125.75")),
				new TicketTypeResponse(22L, 8L, "Free", BigDecimal.ZERO));
	}

	@Test
	void returnsAnEmptyListWhenNoTicketTypesExist() {
		when(this.ticketTypes.findAll()).thenReturn(List.of());

		assertThat(this.service.findAll()).isEmpty();
	}

	// Helpers to build test data with IDs normally generated by the database.
	private static Event event(Long id) {
		Event event = new Event("Java Day", null, LocalDate.of(2026, 11, 10), "Online", 50);
		ReflectionTestUtils.setField(event, "eventId", id);
		return event;
	}

	private static TicketType ticketType(Long id, Event event, String name, BigDecimal price) {
		TicketType ticketType = new TicketType(event, name, price);
		ReflectionTestUtils.setField(ticketType, "ticketTypeId", id);
		return ticketType;
	}

}
